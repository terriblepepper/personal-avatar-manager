_TABLE_OR_INDEX = re.compile(r'^(\s*CREATE\s+(?:UNIQUE\s+)?(?:TABLE|INDEX)\s+)(?!IF\s+NOT\s+EXISTS\b)', re.I)
_ROUTINE = re.compile(r'^(\s*)CREATE\s+(?!OR\s+REPLACE\b)', re.I)


def _idempotent(statement):
    """Make the generated DDL safe to replay against an existing database."""
    head = statement.lstrip().upper()
    if head.startswith(('CREATE TRIGGER', 'CREATE FUNCTION')):
        return _ROUTINE.sub(r'\1CREATE OR REPLACE ', statement, count=1)
    if head.startswith(('CREATE TABLE', 'CREATE INDEX', 'CREATE UNIQUE INDEX')):
        return _TABLE_OR_INDEX.sub(r'\1IF NOT EXISTS ', statement, count=1)
    return statement


def install_schema(connection):
    from avatar.core.postgres_helpers import STATEMENTS as HELPERS
    from avatar.core.postgres_schema_runs import STATEMENTS as RUNS
    for statement in [*STATEMENTS, *HELPERS, *RUNS]:
        connection.execute(_idempotent(statement))

    connection.execute("""ALTER TABLE users ADD COLUMN IF NOT EXISTS onboarding_stage
        TEXT NOT NULL DEFAULT 'done' CHECK (onboarding_stage IN ('welcome','tour','done'))""")

